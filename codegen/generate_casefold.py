#!/usr/bin/env python3
"""Generate src/onlyworlds/_casefold.py from the vendored CaseFolding-15.1.0.txt.

The world file's collision check (folder format spec §4.7, OW-18) folds names with
Unicode's simple case folding at the version the fixture set pins: the C and S rows of
``codegen/schema-dist/fixtures/owworld/CaseFolding-15.1.0.txt``, never a runtime's own
``str.casefold()`` (which is full folding, and moves with Python's Unicode version).
The file is not in the wheel, so the table is generated into the package as runs of
``(start, count, stride, delta)``. ``tests/test_worldfile.py`` walks every code point
against the vendored file, so a table that drifts from it fails there too.

Usage:
  python codegen/generate_casefold.py          write the module
  python codegen/generate_casefold.py --check  exit 1 if the committed module is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "schema-dist" / "fixtures" / "owworld" / "CaseFolding-15.1.0.txt"
OUT = HERE.parent / "src" / "onlyworlds" / "_casefold.py"

ROW = re.compile(r"^([0-9A-F]+); ([CS]); ([0-9A-F]+);")


def rows(text: str) -> dict[int, int]:
    """The C and S rows: code point -> its simple fold."""
    out: dict[int, int] = {}
    for line in text.splitlines():
        m = ROW.match(line)
        if m:
            out[int(m.group(1), 16)] = int(m.group(3), 16)
    return out


def runs(table: dict[int, int]) -> list[tuple[int, int, int, int]]:
    """Greedy runs over the sorted code points: one delta, one stride, as long as both hold."""
    points = sorted(table)
    out: list[tuple[int, int, int, int]] = []
    i = 0
    while i < len(points):
        start = points[i]
        delta = table[start] - start
        count, stride = 1, 1
        if i + 1 < len(points) and table[points[i + 1]] - points[i + 1] == delta:
            stride = points[i + 1] - start
            count = 2
            while (
                i + count < len(points)
                and points[i + count] - points[i + count - 1] == stride
                and table[points[i + count]] - points[i + count] == delta
            ):
                count += 1
        out.append((start, count, stride, delta))
        i += count
    return out


def render(table: dict[int, int]) -> str:
    lines = [
        '"""Unicode 15.1 simple case folding, the C and S rows of CaseFolding.txt (spec §4.7, OW-18).',
        "",
        "GENERATED by codegen/generate_casefold.py from the vendored",
        "codegen/schema-dist/fixtures/owworld/CaseFolding-15.1.0.txt. Do not edit by hand.",
        f"{len(table)} rows, as runs of (start, count, stride, delta): code points start, start + stride, ...",
        "(count of them) fold to themselves plus delta.",
        '"""',
        "",
        f"ROWS = {len(table)}",
        "",
        "FOLD_RUNS: tuple[tuple[int, int, int, int], ...] = (",
    ]
    for start, count, stride, delta in runs(table):
        lines.append(f"    (0x{start:04X}, {count}, {stride}, {delta}),")
    lines.append(")")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed module is stale")
    args = parser.parse_args()
    table = rows(SOURCE.read_text(encoding="utf-8"))
    text = render(table)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is stale: run python codegen/generate_casefold.py", file=sys.stderr)
            return 1
        print(f"{OUT.name} current: {len(table)} rows")
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT} ({len(table)} rows, {len(runs(table))} runs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
