#!/usr/bin/env python3
"""Generate src/onlyworlds/_directions.py: the by-links-3d layout's directions table.

``layout_by_links_3d`` packs the groups of a graph apart in directions read from a table: for each count of parts k
from 1 to 37, k unit vectors [x, y, z] spread over the sphere. They are computed once and kept as numbers, so no
runtime's own cosine, sine or cube root is ever called for them and every runtime reads the same doubles. The table is
codegen/layout/directions.json, the same bytes as the npm SDK's copy; the method's shared fixture names it by its
sha256 (``table_sha256``). Each number is written in the shortest form that reads back the same bits (``repr``), a
negative zero as ``-0.0``.

Usage:
  python codegen/generate_directions.py          write the module
  python codegen/generate_directions.py --check  exit 1 if the committed module is stale
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "layout" / "directions.json"
OUT = HERE.parent / "src" / "onlyworlds" / "_directions.py"
K_MAX = 37


def _number(text: str) -> float:
    """A JSON number as a double, a ``-0`` written without a point kept as -0.0 (``int("-0")`` would lose the sign)."""
    return float(text)


def build() -> str:
    """The module's text, from the table's ``directions``."""
    raw = SOURCE.read_bytes()
    table = json.loads(raw.decode("utf-8"), parse_int=_number, parse_float=_number)
    if table.get("k_max") != K_MAX:
        raise ValueError(f"directions.json: k_max is {table.get('k_max')!r}, not {K_MAX}")
    dirs = table["directions"]
    if sorted(dirs, key=int) != [str(k) for k in range(1, K_MAX + 1)]:
        raise ValueError(f"directions.json holds k = 1 to {K_MAX}, each once")
    lines = [
        '"""The by-links-3d layout\'s directions table.',
        "",
        "GENERATED by codegen/generate_directions.py from codegen/layout/directions.json (sha256",
        f"{hashlib.sha256(raw).hexdigest()}). Do not edit by hand. DIRECTIONS[str(k)]: for k parts",
        "(1 to 37), k unit vectors (x, y, z), float64 written in the shortest form that reads back the same bits.",
        '"""',
        "",
        "DIRECTIONS: dict[str, tuple[tuple[float, float, float], ...]] = {",
    ]
    for k in range(1, K_MAX + 1):
        row = dirs[str(k)]
        if len(row) != k or any(len(p) != 3 for p in row):
            raise ValueError(f"directions.json: k = {k} does not hold {k} directions of three numbers")
        cells = []
        for p in row:
            for v in p:
                if not isinstance(v, float) or not math.isfinite(v):
                    raise ValueError(f"directions.json: k = {k} holds a number that is not finite")
                if struct.pack("<d", float(repr(v))) != struct.pack("<d", v):
                    raise ValueError(f"directions.json: k = {k} holds a number that does not read back")
            cells.append(f"({p[0]!r}, {p[1]!r}, {p[2]!r}),")
        if k == 1:  # the shape ruff format gives a one-point tuple
            lines.append(f'    "{k}": ({cells[0]}),')
            continue
        lines.append(f'    "{k}": (')
        lines.extend(f"        {cell}" for cell in cells)
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed module is stale")
    args = parser.parse_args()
    text = build()
    if args.check:
        if not OUT.exists() or OUT.read_bytes() != text.encode("utf-8"):
            print(
                f"{OUT.relative_to(HERE.parent)} is stale: run python codegen/generate_directions.py", file=sys.stderr
            )
            return 1
        print(f"{OUT.relative_to(HERE.parent)} is current")
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(HERE.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
