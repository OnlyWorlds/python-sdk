#!/usr/bin/env python3
"""Generate src/onlyworlds/_nfc.py from the vendored UnicodeData and CompositionExclusions 15.1.

The world file's collision check (folder format spec §4.7, OW-18) normalises names to NFC
before it folds them, and since schema-dist serial 57 that NFC is Unicode's own at the
version the fixture set pins: built from ``UnicodeData-15.1.0.txt`` and
``CompositionExclusions-15.1.0.txt`` in ``codegen/schema-dist/fixtures/owworld/``, never a
runtime's ``unicodedata`` (which is the interpreter's Unicode: 15.0 on Python 3.12, 16.0 on
3.14). The files are not in the wheel, so three tables are generated into the package:

- ``CLASS_RUNS``: ``(start, count, class)``, the nonzero canonical combining classes (field 3)
  as runs; every other code point is class 0.
- ``DECOMPOSITIONS``: ``(code point, first[, second])``, every canonical decomposition mapping
  (field 5 without a ``<tag>``), one level deep. Hangul syllables are not listed in the file
  and decompose by arithmetic.
- ``EXCLUSIONS``: the code points CompositionExclusions lists uncommented (script-specific and
  post composition version). Singletons and non-starter decompositions are derived at runtime.

``tests/test_worldfile.py`` runs every line of NormalizationTest-15.1.0.txt through the NFC
built from these tables, and checks this module is current.

Usage:
  python codegen/generate_nfc.py          write the module
  python codegen/generate_nfc.py --check  exit 1 if the committed module is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE_DIR = HERE / "schema-dist" / "fixtures" / "owworld"
UNICODE_DATA = SOURCE_DIR / "UnicodeData-15.1.0.txt"
EXCLUSIONS = SOURCE_DIR / "CompositionExclusions-15.1.0.txt"
OUT = HERE.parent / "src" / "onlyworlds" / "_nfc.py"

EXCLUSION_ROW = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*#")


def unicode_data(text: str) -> tuple[dict[int, int], dict[int, tuple[int, ...]]]:
    """Field 3 (nonzero classes) and field 5 (canonical mappings only) of UnicodeData.txt."""
    classes: dict[int, int] = {}
    mappings: dict[int, tuple[int, ...]] = {}
    for line in text.splitlines():
        if not line:
            continue
        f = line.split(";")
        cp = int(f[0], 16)
        if int(f[3]):
            classes[cp] = int(f[3])
        if f[5] and not f[5].startswith("<"):
            to = tuple(int(h, 16) for h in f[5].split(" "))
            if not 1 <= len(to) <= 2:
                raise ValueError(f"U+{cp:04X}: a canonical mapping of {len(to)}")
            mappings[cp] = to
    return classes, mappings


def exclusions(text: str) -> list[int]:
    """The uncommented code points (and ranges) of CompositionExclusions.txt."""
    out: list[int] = []
    for line in text.splitlines():
        m = EXCLUSION_ROW.match(line)
        if m:
            a = int(m.group(1), 16)
            z = int(m.group(2), 16) if m.group(2) else a
            out.extend(range(a, z + 1))
    return out


def class_runs(classes: dict[int, int]) -> list[tuple[int, int, int]]:
    """Consecutive code points of one class, as ``(start, count, class)``."""
    out: list[tuple[int, int, int]] = []
    for cp in sorted(classes):
        if out:
            start, count, cls = out[-1]
            if cp == start + count and classes[cp] == cls:
                out[-1] = (start, count + 1, cls)
                continue
        out.append((cp, 1, classes[cp]))
    return out


def render(classes: dict[int, int], mappings: dict[int, tuple[int, ...]], excluded: list[int]) -> str:
    runs = class_runs(classes)
    lines = [
        '"""Unicode 15.1 NFC data, from UnicodeData.txt and CompositionExclusions.txt (spec §4.7, OW-18).',
        "",
        "GENERATED by codegen/generate_nfc.py from the vendored",
        "codegen/schema-dist/fixtures/owworld/UnicodeData-15.1.0.txt and CompositionExclusions-15.1.0.txt.",
        "Do not edit by hand. CLASS_RUNS: (start, count, class), the nonzero canonical combining classes.",
        "DECOMPOSITIONS: (code point, first[, second]), the canonical mappings, one level deep (Hangul by",
        "arithmetic). EXCLUSIONS: the listed composition exclusions; singletons and non-starter",
        "decompositions are derived from the other two.",
        '"""',
        "",
        f"CLASSES = {len(classes)}",
        "",
        "CLASS_RUNS: tuple[tuple[int, int, int], ...] = (",
    ]
    lines += [f"    (0x{s:04X}, {n}, {c})," for s, n, c in runs]
    lines += [")", "", "DECOMPOSITIONS: tuple[tuple[int, ...], ...] = ("]
    lines += ["    (" + ", ".join(f"0x{x:04X}" for x in (cp, *mappings[cp])) + ")," for cp in sorted(mappings)]
    lines += [")", "", "EXCLUSIONS: tuple[int, ...] = ("]
    lines += [f"    0x{cp:04X}," for cp in excluded]
    lines.append(")")
    return "\n".join(lines) + "\n"


def build() -> tuple[str, str]:
    classes, mappings = unicode_data(UNICODE_DATA.read_text(encoding="utf-8"))
    excluded = exclusions(EXCLUSIONS.read_text(encoding="utf-8"))
    runs = len(class_runs(classes))
    summary = f"{len(classes)} classes in {runs} runs, {len(mappings)} mappings, {len(excluded)} exclusions"
    return render(classes, mappings, excluded), summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed module is stale")
    args = parser.parse_args()
    text, summary = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is stale: run python codegen/generate_nfc.py", file=sys.stderr)
            return 1
        print(f"{OUT.name} current: {summary}")
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT} ({summary})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
