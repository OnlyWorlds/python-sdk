#!/usr/bin/env python3
"""Generate src/onlyworlds/_anchors.py: the by-kind layout's anchor table and the colour groups' order.

``layout_by_kind`` starts each kind of element at a point on a circle and pulls it back there. The method is chaotic:
one anchor one unit in the last place off moves a large world's picture by a fifth of its frame. ``cos`` and ``sin``
are not correctly rounded and differ between language runtimes, so the anchors are never computed at run time: they
are one table of 253 points (for k kinds, k = 1 to 22, the k points), the same float64 values in every package, read
from the shared fixture ``tests/fixtures/layout/by-kind.json`` (its ``anchors``). The colour groups' order comes from
the distribution's ``presentation.json`` (``colors.order``).

Usage:
  python codegen/generate_anchors.py          write the module
  python codegen/generate_anchors.py --check  exit 1 if the committed module is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIXTURE = HERE.parent / "tests" / "fixtures" / "layout" / "by-kind.json"
PRESENTATION = HERE / "schema-dist" / "presentation.json"
OUT = HERE.parent / "src" / "onlyworlds" / "_anchors.py"
KINDS = 22


def build() -> str:
    """The module's text, from the fixture's anchors and the presentation defaults' group order."""
    anchors = json.loads(FIXTURE.read_text(encoding="utf-8"))["anchors"]
    order = json.loads(PRESENTATION.read_text(encoding="utf-8"))["colors"]["order"]
    if sorted(anchors, key=int) != [str(k) for k in range(1, KINDS + 1)]:
        raise ValueError(f"the anchor table holds k = 1 to {KINDS}, each once")
    lines = [
        '"""The by-kind layout\'s anchors and the colour groups\' order.',
        "",
        "GENERATED by codegen/generate_anchors.py from tests/fixtures/layout/by-kind.json (``anchors``) and",
        "codegen/schema-dist/presentation.json (``colors.order``). Do not edit by hand. ANCHORS[k]: for k kinds",
        "(1 to 22), the k points, float64 written in the shortest form that reads back the same bits.",
        '"""',
        "",
        "GROUP_ORDER: tuple[str, ...] = (" + ", ".join(json.dumps(g) for g in order) + ")",
        "",
        "ANCHORS: tuple[tuple[tuple[float, float], ...], ...] = (",
        "    (),",
    ]
    for k in range(1, KINDS + 1):
        points = anchors[str(k)]
        if len(points) != k or any(len(p) != 2 for p in points):
            raise ValueError(f"anchors[{k}] is {k} points of two numbers")
        rows = [f"({float(x)!r}, {float(y)!r})," for x, y in points]
        if k == 1:  # the shape ruff format gives a one-point tuple
            lines.append(f"    ({rows[0]}),")
            continue
        lines.append("    (")
        lines.extend(f"        {row}" for row in rows)
        lines.append("    ),")
    lines.append(")")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed module is stale")
    args = parser.parse_args()
    text = build()
    if args.check:
        if not OUT.exists() or OUT.read_bytes() != text.encode("utf-8"):
            print(f"{OUT.relative_to(HERE.parent)} is stale: run python codegen/generate_anchors.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(HERE.parent)} is current")
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(HERE.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
