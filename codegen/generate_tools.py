#!/usr/bin/env python3
"""Generate src/onlyworlds/_tools.py (TOOLS) from the OnlyWorlds tools list.

The list (github.com/OnlyWorlds/tools, tools.json) is vendored byte for byte at codegen/tools/tools.json and
pinned in codegen/tools-pin.json (the commit and the file's sha256); the npm SDK pins the same commit. A new
listing reaches a surface at the package's next release, as the schema pin does. Only the keys openers_for reads
are baked (id, name, url, client, rung, open); the rest of each row (the checks, the maker) stays in the list.

Usage:
  python codegen/generate_tools.py                 check the vendored file against the pin, write the module
  python codegen/generate_tools.py --check         exit 1 if the vendored file or the module is stale
  python codegen/generate_tools.py --repin COMMIT  vendor tools.json as GitHub serves it at COMMIT, pin it, write
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
VENDORED = ROOT / "codegen" / "tools" / "tools.json"
PIN = ROOT / "codegen" / "tools-pin.json"
OUT = ROOT / "src" / "onlyworlds" / "_tools.py"
REPO = "https://github.com/OnlyWorlds/tools"
KEYS = ("id", "name", "url", "client", "rung", "open")


def literal(value: Any, indent: int) -> str:
    """A JSON value as a Python literal, one key a line, in the list's own order."""
    pad = "    " * indent
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, dict):
        inner = "".join(f'{pad}    "{k}": {literal(v, indent + 1)},\n' for k, v in value.items())
        return "{\n" + inner + pad + "}"
    raise SystemExit(f"tools: a value this generator does not bake: {value!r}")


def render(data: bytes, pin: dict[str, Any]) -> str:
    doc = json.loads(data.decode("utf-8"))
    if doc.get("format") != 1:
        raise SystemExit(f"tools: tools.json format {doc.get('format')!r}; this generator reads format 1")
    if not isinstance(doc.get("tools"), list):
        raise SystemExit("tools: tools.json has no tools array")
    rows = []
    for t in doc["tools"]:
        missing = [k for k in KEYS if k not in t]
        if missing:
            raise SystemExit(f"tools: row {t.get('id')!r} has no {', '.join(missing)}")
        rows.append("    " + literal({k: t[k] for k in KEYS}, 1) + ",\n")
    return (
        "# GENERATED by codegen/generate_tools.py from the OnlyWorlds tools list. Do not hand-edit: the list is"
        " changed\n"
        "# upstream, repinned (python codegen/generate_tools.py --repin <commit>) and regenerated.\n"
        f"# Source: {REPO} @ {pin['commit']}, tools.json sha256 {pin['sha256']}\n"
        "\n"
        '"""The OnlyWorlds tools list\'s rows (format 1), in the list\'s order, as of this release."""\n'
        "\n"
        "from .openers import Tool\n"
        "\n"
        "#: The keys openers_for reads, per row.\n"
        "TOOLS: tuple[Tool, ...] = (\n" + "".join(rows) + ")\n"
    )


def read_pinned() -> tuple[dict[str, Any], bytes]:
    pin: dict[str, Any] = json.loads(PIN.read_text(encoding="utf-8"))
    data = VENDORED.read_bytes()
    got = hashlib.sha256(data).hexdigest()
    if got != pin["sha256"]:
        raise SystemExit(f"tools: codegen/tools/tools.json is sha256 {got}; the pin says {pin['sha256']}")
    return pin, data


def main() -> int:
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--repin", metavar="COMMIT")
    args = ap.parse_args()
    if args.repin is not None:
        if not re.fullmatch(r"[0-9a-f]{40}", args.repin):
            raise SystemExit("tools: --repin takes the full 40-hex commit")
        url = f"https://raw.githubusercontent.com/OnlyWorlds/tools/{args.repin}/tools.json"
        with urllib.request.urlopen(url, timeout=30) as res:
            data = res.read()
        pin = {
            "_what": "The recorded pin for the vendored OnlyWorlds tools list (codegen/tools/tools.json, byte for byte"
            " as GitHub serves it at the commit). Do not edit by hand: python codegen/generate_tools.py --repin"
            " <commit>, and review the diff. Kept equal to the npm SDK's pin (codegen/tools-pin.json) on purpose.",
            "repo": REPO,
            "commit": args.repin,
            "sha256": hashlib.sha256(data).hexdigest(),
            "pinned_at": datetime.date.today().isoformat(),
        }
        VENDORED.parent.mkdir(exist_ok=True)
        VENDORED.write_bytes(data)
        PIN.write_bytes((json.dumps(pin, indent=2) + "\n").encode("utf-8"))
        OUT.write_bytes(render(data, pin).encode("utf-8"))
        print(f"pinned {args.repin}, sha256 {pin['sha256']}; wrote {OUT.name}")
        return 0
    pin, data = read_pinned()
    text = render(data, pin)
    if args.check:
        current = OUT.read_bytes().decode("utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"STALE: {OUT} does not match what the pinned tools list generates", file=sys.stderr)
            return 1
        print(f"ok: {OUT.name} matches the tools list at {pin['commit']}")
        return 0
    OUT.write_bytes(text.encode("utf-8"))  # bytes: LF on every platform
    print(f"wrote {OUT} from the tools list at {pin['commit']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
